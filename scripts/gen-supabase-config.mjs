// Writes src/app/core/supabase.config.ts (git-ignored) from SUPABASE_URL / SUPABASE_ANON_KEY.
// - Env vars set  -> file is (re)generated from them.
// - Env vars unset and file exists -> file is left untouched (local dev).
// - Env vars unset and no file -> blank file is written so the build still passes (Google button hidden).
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../src/app/core/supabase.config.ts', import.meta.url));
const url = process.env.SUPABASE_URL?.trim() ?? '';
const key = process.env.SUPABASE_ANON_KEY?.trim() ?? '';

if (!url && !key && existsSync(target)) {
  console.log('[supabase-config] no env vars set; keeping existing supabase.config.ts');
  process.exit(0);
}
if (Boolean(url) !== Boolean(key)) {
  console.error('[supabase-config] set both SUPABASE_URL and SUPABASE_ANON_KEY (or neither).');
  process.exit(1);
}

const q = (s) => JSON.stringify(s);
writeFileSync(
  target,
  `// Generated by scripts/gen-supabase-config.mjs — do not edit or commit.
export const SUPABASE_URL = ${q(url)};
export const SUPABASE_ANON_KEY = ${q(key)};

export const supabaseConfigured = Boolean(SUPABASE_URL && SUPABASE_ANON_KEY);
`,
);
console.log(`[supabase-config] wrote supabase.config.ts (${url ? 'configured' : 'blank — Google sign-in hidden'})`);
